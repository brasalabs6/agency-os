export const messages: Record<Locale, Record<MessageKey, string>> = {
  "pt-BR": ptBR,
  en,
};

export function normalizeLocale(value?: string | null): Locale {
  return value === "en" ? "en" : DEFAULT_LOCALE;
}

export function formatMessage(template: string, vars?: Record<string, string | number>) {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? `{${key}}`));
}

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>) {
  return formatMessage(messages[locale][key] ?? messages[DEFAULT_LOCALE][key] ?? key, vars);
}

export function intlLocale(locale: Locale) {
  return locale === "en" ? "en-US" : "pt-BR";
}
